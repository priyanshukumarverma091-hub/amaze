from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable

from backend.schemas import (
    Decision,
    TakeoverReport,
    WorkItem,
    WorkStatus,
)
from backend.reasoning.context_engine import ProjectContext
from backend.reasoning.conflict_detector import Conflict
from backend.reasoning.confidence import ConfidenceResult


@dataclass
class TakeoverEngine:
    """
    Deterministic takeover report generator.

    Converts structured project context into a TakeoverReport.
    No LLM is used here.
    """

    def generate(
        self,
        context: ProjectContext,
        decisions: Iterable[Decision] | None = None,
        conflicts: Iterable[Conflict] | None = None,
        confidence: dict[str, ConfidenceResult] | None = None,
        target_role: str | None = None,
        previous_owner: str | None = None,
    ) -> TakeoverReport:

        decisions = list(decisions or [])
        conflicts = list(conflicts or [])
        confidence = confidence or {}

        completed_work = self._build_work_items(
            context.completed_work,
            WorkStatus.DONE,
        )

        active_work = self._build_work_items(
            context.active_work,
            WorkStatus.IN_PROGRESS,
        )

        blocked_work = self._build_work_items(
            context.blocked_work,
            WorkStatus.BLOCKED,
        )

        planned_work = self._build_work_items(
            context.planned_work,
            WorkStatus.PLANNED,
        )

        abandoned_work = self._build_work_items(
            context.abandoned_work,
            WorkStatus.ABANDONED,
        )

        unknown_work = self._build_work_items(
            context.unknown_work,
            WorkStatus.UNKNOWN,
        )

        important_decisions = self._build_decisions(
            decisions=decisions,
            context=context,
        )

        risks = self._build_risks(
            context=context,
            conflicts=conflicts,
            confidence=confidence,
        )

        recommended_first_steps = self._build_first_steps(
            context=context,
            blocked_work=blocked_work,
            active_work=active_work,
            planned_work=planned_work,
            conflicts=conflicts,
        )

        evidence_ids = self._collect_evidence_ids(
            context=context,
            decisions=decisions,
        )

        return TakeoverReport(
            id=self._build_report_id(
                project=context.project,
                target_role=target_role,
            ),
            project=context.project,
            target_role=target_role or "unknown",
            previous_owner=previous_owner,
            project_summary=context.summary,
            current_state=context.current_state,
            completed_work=completed_work,
            active_work=active_work,
            blocked_work=blocked_work,
            dependencies=list(context.dependencies),
            important_decisions=important_decisions,
            risks=risks,
            recommended_first_steps=recommended_first_steps,
            evidence_ids=evidence_ids,
        )

    # ------------------------------------------------------------------
    # WORK ITEMS
    # ------------------------------------------------------------------

    def _build_work_items(
        self,
        items: Iterable,
        status: WorkStatus,
    ) -> list[WorkItem]:

        result: list[WorkItem] = []

        for item in items:
            if item is None:
                continue

            # ContextItem is the normal input type.
            # Read its structured fields instead of converting
            # the complete object into a string.
            title = getattr(item, "title", None)
            description = getattr(item, "description", None)

            if title is None:
                # Backward compatibility if a plain string is supplied.
                title = str(item)

            title = str(title).strip()

            if not title:
                continue

            # Preserve evidence generated by the ContextEngine.
            evidence_ids = getattr(item, "evidence_ids", []) or []

            # Preserve dependency information from ContextEngine.
            dependency_ids = getattr(item, "dependency_ids", []) or []

            result.append(
                WorkItem(
                    title=title,
                    description=(
                        str(description).strip()
                        if description
                        else None
                    ),
                    status=status,
                    evidence_ids=self._unique(
                        str(evidence_id)
                        for evidence_id in evidence_ids
                        if evidence_id
                    ),
                    dependencies=self._unique(
                        str(dependency_id)
                        for dependency_id in dependency_ids
                        if dependency_id
                    ),
                )
            )

        return result

    # ------------------------------------------------------------------
    # DECISIONS
    # ------------------------------------------------------------------

    def _build_decisions(
        self,
        decisions: list[Decision],
        context: ProjectContext,
    ) -> list[str]:

        result: list[str] = []

        for decision in decisions:
            text = decision.title.strip()

            if decision.decision:
                text = f"{text}: {decision.decision}"

            if decision.status:
                text += f" [{decision.status.value}]"

            result.append(text)

        # Preserve decisions already discovered by ContextEngine.
        if not result:
            for decision in context.important_decisions:
                if decision:
                    if hasattr(decision, "claim"):
                        claim = getattr(decision, "claim")
                        if claim:
                            result.append(str(claim))
                    else:
                        result.append(str(decision))

        return self._unique(result)

    # ------------------------------------------------------------------
    # RISKS
    # ------------------------------------------------------------------

    def _build_risks(
        self,
        context: ProjectContext,
        conflicts: list[Conflict],
        confidence: dict[str, ConfidenceResult],
    ) -> list[str]:

        risks: list[str] = []

        for item in context.blocked_work:
            if item:
                title = getattr(item, "title", str(item))

                risks.append(
                    f"Blocked work requires attention: {title}"
                )

        for conflict in conflicts:
            description = self._conflict_description(conflict)

            if description:
                risks.append(
                    f"Unresolved conflict: {description}"
                )

        for evidence_id, result in confidence.items():
            score = getattr(result, "score", None)

            if score is None:
                continue

            try:
                score = float(score)
            except (TypeError, ValueError):
                continue

            if score < 0.5:
                risks.append(
                    f"Low-confidence evidence: {evidence_id} "
                    f"(confidence={score:.2f})"
                )

        return self._unique(risks)

    # ------------------------------------------------------------------
    # FIRST STEPS
    # ------------------------------------------------------------------

    def _build_first_steps(
        self,
        context: ProjectContext,
        blocked_work: list[WorkItem],
        active_work: list[WorkItem],
        planned_work: list[WorkItem],
        conflicts: list[Conflict],
    ) -> list[str]:

        steps: list[str] = []

        if context.current_state:
            steps.append(
                "Review the current project state and verify it against "
                "the available evidence."
            )

        for item in blocked_work:
            steps.append(
                f"Investigate blocked work: {item.title}"
            )

        for item in active_work:
            steps.append(
                f"Review and continue active work: {item.title}"
            )

        if context.dependencies:
            steps.append(
                "Review project dependencies before starting new work."
            )

        if context.important_decisions:
            steps.append(
                "Review the important project decisions and their evidence."
            )

        if conflicts:
            steps.append(
                "Review unresolved conflicts before making changes "
                "to the affected areas."
            )

        if planned_work:
            steps.append(
                "Review planned work and confirm priorities with the "
                "current project state."
            )

        if not steps:
            steps.append(
                "Review the available project evidence and establish "
                "the current state before making changes."
            )

        return self._unique(steps)

    # ------------------------------------------------------------------
    # EVIDENCE
    # ------------------------------------------------------------------

    def _collect_evidence_ids(
        self,
        context: ProjectContext,
        decisions: list[Decision],
    ) -> list[str]:

        evidence_ids = list(context.evidence_ids)

        for decision in decisions:
            evidence_ids.extend(decision.evidence_ids)

        # Also collect evidence directly from every work item.
        for collection_name in (
            "completed_work",
            "active_work",
            "blocked_work",
            "planned_work",
            "abandoned_work",
            "unknown_work",
        ):
            collection = getattr(context, collection_name, []) or []

            for item in collection:
                item_evidence = getattr(item, "evidence_ids", []) or []
                evidence_ids.extend(item_evidence)

        return self._unique(
            str(evidence_id)
            for evidence_id in evidence_ids
            if evidence_id
        )

    # ------------------------------------------------------------------
    # CONFLICT HELPERS
    # ------------------------------------------------------------------

    @staticmethod
    def _conflict_description(conflict: Conflict) -> str:

        if hasattr(conflict, "description"):
            description = getattr(conflict, "description")

            if description:
                return str(description)

        if hasattr(conflict, "message"):
            message = getattr(conflict, "message")

            if message:
                return str(message)

        if hasattr(conflict, "claim_a") and hasattr(conflict, "claim_b"):
            return (
                f"{getattr(conflict, 'claim_a')} "
                f"vs "
                f"{getattr(conflict, 'claim_b')}"
            )

        return str(conflict)

    # ------------------------------------------------------------------
    # GENERAL HELPERS
    # ------------------------------------------------------------------

    @staticmethod
    def _build_report_id(
        project: str | None,
        target_role: str | None,
    ) -> str:

        project_part = (
            project.strip().lower().replace(" ", "-")
            if project
            else "unknown-project"
        )

        role_part = (
            target_role.strip().lower().replace(" ", "-")
            if target_role
            else "unknown-role"
        )

        return f"takeover-{project_part}-{role_part}"

    @staticmethod
    def _unique(items: Iterable[str]) -> list[str]:

        result: list[str] = []
        seen: set[str] = set()

        for item in items:
            if item is None:
                continue

            value = str(item).strip()

            if not value:
                continue

            if value not in seen:
                seen.add(value)
                result.append(value)

        return result